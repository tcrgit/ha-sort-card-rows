/**
 * Home Assistant Frontend Plugin: Sort Card Rows (v1.1.0)
 *
 * Orders rows inside dashboard cards using:
 *   1. Global pinned entities (drag-and-drop list in Configure)
 *   2. Native Home Assistant labels on devices & entities (sort-0..9, sort-top, sort-bottom, sort-0.5)
 *   3. Device class priority order (plus sort-<device_class> overrides)
 *   4. Priority keywords within tied groups
 *   5. Alphabetical tie-breaker by display name
 *
 * Also supports hiding card header toggles for configured Areas or `no-header-toggle` labels,
 * automatically pauses sorting while Lovelace Edit Mode is active, and skips Home Dashboard
 * summary sections with fewer than two sortable entities.
 */
(function () {
  const PLUGIN_NAME = "Sort Card Rows";
  const PLUGIN_VERSION = "1.1.0";
  const STORAGE_KEY = "sort_card_rows_settings_v1";
  const DEFAULT_RANK = 50;
  const TARGET_TAGS = new Set([
    "hui-card",
    "hui-entities-card",
    "hui-grid-card",
    "hui-section",
  ]);

  let settings = {
    pinned_entities: [],
    no_header_toggle_areas: [],
    device_class_order: [
      "temperature",
      "humidity",
      "illuminance",
      "pressure",
      "atmospheric_pressure",
      "radon",
      "carbon_dioxide",
      "battery",
    ],
    keyword_order: [],
    auto_dashboards_only: true,
  };

  try {
    const cached = localStorage.getItem(STORAGE_KEY);
    if (cached) {
      settings = { ...settings, ...JSON.parse(cached) };
    }
  } catch (_) {}

  const patchedCards = new Set();
  let lastEditMode = null;

  function getHass() {
    return document.querySelector("home-assistant")?.hass || null;
  }

  function queryShadowSelector(root, selector) {
    if (!root) return null;
    if (root.querySelector) {
      const found = root.querySelector(selector);
      if (found) return found;
    }
    if (root.querySelectorAll) {
      for (const el of root.querySelectorAll("*")) {
        if (el.shadowRoot) {
          const found = queryShadowSelector(el.shadowRoot, selector);
          if (found) return found;
        }
      }
    }
    return null;
  }

  function isLovelaceEditMode() {
    if (window.location.search.includes("edit=1")) return true;
    const lovelaceEl = queryShadowSelector(document, "ha-panel-lovelace");
    return Boolean(
      lovelaceEl && lovelaceEl.lovelace && lovelaceEl.lovelace.editMode
    );
  }

  function isAutoGeneratedDashboard() {
    const lovelaceEl = queryShadowSelector(document, "ha-panel-lovelace");
    if (!lovelaceEl || !lovelaceEl.lovelace) return true;
    const ll = lovelaceEl.lovelace;
    if (ll.mode === "generated") return true;
    const cfg = ll.config;
    if (!cfg || typeof cfg !== "object") return false;
    if (cfg.strategy) return true;
    if (Array.isArray(cfg.views)) {
      const path = window.location.pathname.split("/").pop();
      const activeView =
        cfg.views.find(function (v) {
          return String(v.path || "") === path;
        }) || cfg.views[Number(path) || 0];
      if (activeView && activeView.strategy) return true;
    }
    return false;
  }

  function walkShadowTrees(root, callback) {
    if (!root || !root.querySelectorAll) return;
    for (const el of root.querySelectorAll("*")) {
      callback(el);
      if (el.shadowRoot) {
        walkShadowTrees(el.shadowRoot, callback);
      }
    }
  }

  function arraysHaveSameOrder(a, b) {
    if (a === b) return true;
    if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) {
      return false;
    }
    for (let i = 0; i < a.length; i++) {
      if (a[i] !== b[i]) return false;
    }
    return true;
  }

  function parseSortLabel(rawLabel) {
    const lower = String(rawLabel).toLowerCase().trim();

    const tupleMatch = lower.match(
      /^sort[\s\-_]+([+-]?(?:\d+\.?\d*|\.\d+))[\s\-_]+([+-]?(?:\d+\.?\d*|\.\d+))$/
    );
    if (tupleMatch) {
      const [, gStr, iStr] = tupleMatch;
      return { tuple: [parseFloat(gStr), parseFloat(iStr)] };
    }

    const compact = lower.replace(/[^a-z0-9.]/g, "");
    if (!compact.startsWith("sort") || compact.length <= 4) return null;

    const rest = compact.slice(4);
    if (rest === "top" || rest === "first") return { rank: -999 };
    if (rest === "bottom" || rest === "last") return { rank: 999 };

    if (/^[+-]?(?:\d+\.?\d*|\.\d+)$/.test(rest)) {
      const num = parseFloat(rest);
      if (!Number.isNaN(num)) return { rank: num };
    }

    return { deviceClass: rest };
  }

  function extractLabelInfo(labels) {
    let rank = null;
    let tuple = null;
    let deviceClass = null;

    for (const lbl of labels || []) {
      const parsed = parseSortLabel(lbl);
      if (!parsed) continue;
      if (parsed.tuple && tuple === null) tuple = parsed.tuple;
      if (parsed.rank !== undefined && rank === null) rank = parsed.rank;
      if (parsed.deviceClass && deviceClass === null) {
        deviceClass = parsed.deviceClass;
      }
    }
    return { rank, tuple, deviceClass };
  }

  function getEntityIdFromItem(item) {
    if (typeof item === "string") return item;
    if (item && typeof item === "object") {
      if (typeof item.entity === "string") return item.entity;
      if (typeof item.entity_id === "string") return item.entity_id;
    }
    return null;
  }

  function buildSortKey(entityId, item, hass) {
    const pinIndex = settings.pinned_entities.indexOf(entityId);
    const pinRank = pinIndex >= 0 ? pinIndex : Number.MAX_SAFE_INTEGER;

    const entityMeta = hass?.entities?.[entityId];
    const device = entityMeta?.device_id
      ? hass?.devices?.[entityMeta.device_id]
      : null;
    const parentDevice = device?.via_device_id
      ? hass?.devices?.[device.via_device_id]
      : null;

    const entInfo = extractLabelInfo(entityMeta?.labels);
    const devInfo = extractLabelInfo(device?.labels);
    const parentInfo = extractLabelInfo(parentDevice?.labels);

    const effectiveDeviceRank =
      devInfo.rank !== null ? devInfo.rank : parentInfo.rank;

    let groupRank = DEFAULT_RANK;
    let itemRank = DEFAULT_RANK;

    if (entInfo.tuple) {
      [groupRank, itemRank] = entInfo.tuple;
    } else if (effectiveDeviceRank !== null) {
      groupRank = effectiveDeviceRank;
      itemRank = entInfo.rank !== null ? entInfo.rank : DEFAULT_RANK;
    } else if (entInfo.rank !== null) {
      groupRank = entInfo.rank;
      itemRank = DEFAULT_RANK;
    }

    const stateObj = hass?.states?.[entityId];
    const rawDeviceClass =
      entInfo.deviceClass || stateObj?.attributes?.device_class || "";
    const normDeviceClass = String(rawDeviceClass)
      .toLowerCase()
      .replace(/[^a-z0-9]/g, "");

    const normalizedClassList = settings.device_class_order.map((c) =>
      c.replace(/[^a-z0-9]/g, "")
    );
    const classIdx = normDeviceClass
      ? normalizedClassList.indexOf(normDeviceClass)
      : -1;
    const deviceClassRank = classIdx >= 0 ? classIdx : 999;

    const rawName =
      (item &&
        typeof item === "object" &&
        typeof item.name === "string" &&
        item.name) ||
      (typeof stateObj?.attributes?.friendly_name === "string" &&
        stateObj.attributes.friendly_name) ||
      entityId;
    const displayName = String(rawName).toLowerCase();

    let keywordRank = 999;
    for (let i = 0; i < settings.keyword_order.length; i++) {
      if (displayName.includes(settings.keyword_order[i])) {
        keywordRank = i;
        break;
      }
    }

    return [
      pinRank,
      groupRank,
      itemRank,
      deviceClassRank,
      keywordRank,
      displayName,
    ];
  }

  function compareKeys(a, b) {
    for (let i = 0; i < a.length - 1; i++) {
      if (a[i] !== b[i]) return a[i] - b[i];
    }
    return a[a.length - 1].localeCompare(b[b.length - 1], undefined, {
      numeric: true,
      sensitivity: "base",
    });
  }

  function sortItems(items, hass) {
    if (!Array.isArray(items) || items.length < 2) return items;
    if (isLovelaceEditMode()) return items;
    if (settings.auto_dashboards_only && !isAutoGeneratedDashboard()) {
      return items;
    }

    const keyed = items.map((item, idx) => {
      const entityId = getEntityIdFromItem(item);
      return {
        item,
        idx,
        entityId,
        key: entityId ? buildSortKey(entityId, item, hass) : null,
      };
    });

    const sortableCount = keyed.filter((entry) => Boolean(entry.entityId)).length;
    if (sortableCount < 2) return items;

    keyed.sort((a, b) => {
      if (a.key && b.key) {
        const diff = compareKeys(a.key, b.key);
        return diff !== 0 ? diff : a.idx - b.idx;
      }
      if (a.key) return -1;
      if (b.key) return 1;
      return a.idx - b.idx;
    });

    const sorted = keyed.map((entry) => entry.item);
    return arraysHaveSameOrder(items, sorted) ? items : sorted;
  }

  function hasHideToggleLabel(labels) {
    for (const lbl of labels || []) {
      const norm = String(lbl).toLowerCase().replace(/[^a-z0-9]/g, "");
      if (norm === "noheadertoggle" || norm === "hideheadertoggle") return true;
    }
    return false;
  }

  function shouldHideHeaderToggle(config, hass) {
    const targetAreas = new Set(settings.no_header_toggle_areas || []);
    const titleLower = String(config.title || "").trim().toLowerCase();

    if (hass && hass.areas && titleLower) {
      for (const area of Object.values(hass.areas)) {
        if (String(area.name || "").trim().toLowerCase() === titleLower) {
          if (
            targetAreas.has(area.area_id) ||
            hasHideToggleLabel(area.labels)
          ) {
            return true;
          }
        }
      }
    }

    for (const item of config.entities || []) {
      const entityId = getEntityIdFromItem(item);
      if (!entityId) continue;
      const ent = hass?.entities?.[entityId];
      const dev = ent?.device_id ? hass?.devices?.[ent.device_id] : null;
      if (hasHideToggleLabel(ent?.labels) || hasHideToggleLabel(dev?.labels)) {
        return true;
      }
      const areaId = ent?.area_id || dev?.area_id;
      if (areaId) {
        if (targetAreas.has(areaId)) return true;
        if (hasHideToggleLabel(hass?.areas?.[areaId]?.labels)) return true;
      }
    }
    return false;
  }

  function applySortToConfig(config, hass) {
    if (!config || typeof config !== "object") return config;
    if (isLovelaceEditMode()) return config;

    const nextEntities = Array.isArray(config.entities)
      ? sortItems(config.entities, hass)
      : config.entities;
    const nextCards = Array.isArray(config.cards)
      ? sortItems(config.cards, hass)
      : config.cards;
    const hideToggle = Array.isArray(config.entities)
      ? shouldHideHeaderToggle(config, hass)
      : false;

    const entitiesChanged = nextEntities !== config.entities;
    const cardsChanged = nextCards !== config.cards;
    const toggleChanged = hideToggle && config.show_header_toggle !== false;

    if (!entitiesChanged && !cardsChanged && !toggleChanged) {
      return config;
    }

    const updated = {
      ...config,
      ...(toggleChanged ? { show_header_toggle: false } : {}),
      ...(entitiesChanged ? { entities: nextEntities } : {}),
      ...(cardsChanged ? { cards: nextCards } : {}),
    };
    Object.defineProperty(updated, "__sortApplied", {
      value: true,
      enumerable: false,
    });
    return updated;
  }

  function configOrderSignature(config) {
    if (!config || typeof config !== "object") return "";
    const parts = [];
    if (Array.isArray(config.entities)) {
      parts.push("e:" + config.entities.map(getEntityIdFromItem).join(","));
    }
    if (Array.isArray(config.cards)) {
      parts.push("c:" + config.cards.map(getEntityIdFromItem).join(","));
    }
    return parts.join("|");
  }

  function captureRawConfig(el, config) {
    if (config && typeof config === "object" && !config.__sortApplied) {
      el.__sortRawConfig = config;
    }
  }

  function refreshCardElement(el, hass) {
    const current = el._config || el.config;
    if (!current || typeof current !== "object") return;
    if (!el.__sortRawConfig && !current.__sortApplied) {
      el.__sortRawConfig = current;
    }
    const base = el.__sortRawConfig || current;
    const desired = isLovelaceEditMode() ? base : applySortToConfig(base, hass);

    if (configOrderSignature(desired) === configOrderSignature(current)) return;

    if (typeof el.setConfig === "function") {
      el.setConfig(desired);
      if (typeof el.requestUpdate === "function") {
        el.requestUpdate();
      }
    } else if ("config" in el) {
      el.config = desired;
    }
  }

  function reapplyAllMountedCards() {
    const hass = getHass();
    if (!hass || !hass.entities) return;
    lastEditMode = isLovelaceEditMode();
    walkShadowTrees(document, (el) => {
      const tag = el.tagName ? el.tagName.toLowerCase() : "";
      if (TARGET_TAGS.has(tag)) {
        refreshCardElement(el, hass);
      }
    });
  }

  function patchCardElement(tagName) {
    if (patchedCards.has(tagName)) return;
    patchedCards.add(tagName);

    customElements.whenDefined(tagName).then((CardClass) => {
      const proto = CardClass.prototype;

      if (
        typeof proto.setConfig === "function" &&
        !proto.__sortSetConfigPatched
      ) {
        const origSetConfig = proto.setConfig;
        proto.setConfig = function (config) {
          captureRawConfig(this, config);
          const hass = this.hass || getHass();
          return origSetConfig.call(this, applySortToConfig(config, hass));
        };
        proto.__sortSetConfigPatched = true;
      }

      const configDesc = Object.getOwnPropertyDescriptor(proto, "config");
      if (configDesc && configDesc.set && !proto.__sortConfigPropPatched) {
        Object.defineProperty(proto, "config", {
          get: configDesc.get,
          set(val) {
            captureRawConfig(this, val);
            const hass = this.hass || getHass();
            configDesc.set.call(this, applySortToConfig(val, hass));
          },
          configurable: true,
        });
        proto.__sortConfigPropPatched = true;
      }

      let walkProto = proto;
      let hassDesc = null;
      while (walkProto && !hassDesc) {
        hassDesc = Object.getOwnPropertyDescriptor(walkProto, "hass");
        walkProto = Object.getPrototypeOf(walkProto);
      }

      if (hassDesc && hassDesc.set && !proto.__sortHassPatched) {
        Object.defineProperty(proto, "hass", {
          get: hassDesc.get,
          set(newHass) {
            const prevHass = this.hass;
            hassDesc.set.call(this, newHass);
            if (!newHass || !newHass.entities) return;
            const editNow = isLovelaceEditMode();
            const registryChanged =
              !prevHass ||
              prevHass.entities !== newHass.entities ||
              prevHass.devices !== newHass.devices ||
              prevHass.areas !== newHass.areas ||
              this.__sortLastEdit !== editNow;
            if (registryChanged) {
              this.__sortLastEdit = editNow;
              refreshCardElement(this, newHass);
            }
          },
          configurable: true,
        });
        proto.__sortHassPatched = true;
      }

      reapplyAllMountedCards();
    });
  }

  TARGET_TAGS.forEach(patchCardElement);

  function watchEditModeChanges() {
    const currentEdit = isLovelaceEditMode();
    if (lastEditMode !== null && currentEdit !== lastEditMode) {
      reapplyAllMountedCards();
    }
    lastEditMode = currentEdit;
  }

  function logStatus(stage) {
    console.info(
      `[${PLUGIN_NAME}] ${stage} (v${PLUGIN_VERSION}, auto_only=${Boolean(
        settings.auto_dashboards_only
      )}, pinned=${(settings.pinned_entities || []).length}, hidden_headers=${
        (settings.no_header_toggle_areas || []).length
      }).`
    );
  }

  async function syncSettings() {
    try {
      const resp = await fetch("/sort_card_rows/settings.json", {
        cache: "no-store",
      });
      if (!resp.ok) return;
      const fresh = await resp.json();
      settings = { ...settings, ...fresh };
      localStorage.setItem(STORAGE_KEY, JSON.stringify(settings));
      reapplyAllMountedCards();
      logStatus("Synced");
    } catch (err) {
      console.warn(`[${PLUGIN_NAME}] Could not fetch settings:`, err);
    }
  }

  logStatus("Active");
  syncSettings();
  setInterval(watchEditModeChanges, 350);
  setTimeout(reapplyAllMountedCards, 400);
  setTimeout(reapplyAllMountedCards, 1200);
})();
